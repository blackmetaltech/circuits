#!/usr/bin/env bash
# Regenerates every reference CSV in ../../tests/ref from the ngspice decks in this directory.
#
#   scripts/ngspice-ref/run.sh            (needs `ngspice` >= 42 on PATH; the committed CSVs were made with the version in
#                                          tests/ref/ngspice-version.txt)
#
# CI does NOT run this: the CSVs are committed. Each deck runs in batch mode (`ngspice -b`), its .control block resamples the
# transient to a uniform grid (`linearize`) and writes raw columns with `wrdata`; this script prepends the header row (with
# units; the sweep/time/frequency variable is column 1) and converts whitespace-separated columns to CSV. Each file has <= 2000 rows.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$HERE/../../tests/ref"
mkdir -p "$OUT"
cd "$HERE"
rm -rf build && mkdir build
trap 'rm -rf "$HERE/build"' EXIT

# name -> header (comma separated, units in the names). Columns must match the wrdata order in the deck.
declare -A HDR=(
  [01]="time_s,v_in_V,v_out_V"
  [02]="time_s,v_in_V,v_out_V"
  [03a]="time_s,v_src_V,v_out_V,i_src_A"
  [03b]="time_s,v_src_V,v_out_V,i_src_A"
  [04]="vin_V,v_out_V,i_in_A"
  [05]="v_src_V,v_led_V,i_A"
  [06]="time_s,v_src_V,v_base_V,v_coll_V,v_out_V,v_out_noearly_V"
  [07]="vin_V,v_out_V,i_d_A"
  [08]="time_s,v_gate_V,v_drain_V,i_load_A"
  [09]="time_s,v_in_V,v_cap_V,i_L_A"
  [10]="freq_Hz,mag_dB,phase_deg"
  [11]="time_s,v_out_V,v_p_V"
  [12]="time_s,v_sw_V,v_out_V,i_L_A"
  [13]="time_s,v_c1_V,v_c2_V,v_b1_V,v_b2_V"
  [14]="time_s,v_sec_V,v_out_V,i_sec_A"
  [15]="vin_A_V,v_out_V,v_P_V,v_base_V,i_vcc_A"
)
# name -> committed file name
declare -A FILE=(
  [01]="01-diode-clipper" [02]="02-halfwave" [03a]="03-bridge-inrush" [03b]="03-bridge-settled" [04]="04-zener-shunt"
  [05]="05-led-iv" [06]="06-ce-amp" [07]="07-mosfet-vtc" [08]="08-nmos-flyback" [09]="09-rlc-step" [10]="10-sallen-key"
  [11]="11-wien-startup" [12]="12-buck" [13]="13-bjt-astable" [14]="14-bridge-transformer" [15]="15-dtl-nand"
)

{
  ngspice -v | grep -m1 'ngspice-'
  echo "generated by scripts/ngspice-ref/run.sh; options: method=trap reltol=1e-5 abstol=1e-12 vntol=1e-7 gmin=1e-12 temp=tnom=26.85"
} > "$OUT/ngspice-version.txt"

# thermal voltage check
ngspice -b -o build/00.log 00-vt-check.cir > /dev/null 2>&1 || true
grep -h 'VT-CHECK' build/00.log >> "$OUT/ngspice-version.txt" || { echo "VT check failed" >&2; exit 1; }

for deck in 0[1-9]-*.cir 1[0-5]-*.cir; do
  n="${deck%%-*}"
  echo "== $deck"
  ngspice -b -o "build/$n.log" "$deck" > /dev/null 2>&1 || true
  if grep -qiE 'timestep too small|singular matrix|^error' "build/$n.log"; then
    echo "ngspice reported a problem in $deck:" >&2
    grep -iE 'timestep too small|singular matrix|^error' "build/$n.log" >&2
    exit 1
  fi
  for key in "$n" "${n}a" "${n}b"; do
    [[ -f "build/$key.dat" ]] || continue
    h="${HDR[$key]}"
    ncol=$(awk -F, '{print NF; exit}' <<< "$h")
    f="$OUT/${FILE[$key]}.csv"
    { echo "$h"; awk -v nc="$ncol" 'NF>0 { if (NF != nc) { print "bad column count in " FILENAME ": " NF " vs " nc > "/dev/stderr"; exit 1 } s=$1; for (i=2;i<=NF;i++) s=s "," $i; print s }' "build/$key.dat"; } > "$f"
    rows=$(($(wc -l < "$f") - 1))
    if (( rows > 2000 )); then echo "$f has $rows rows (> 2000)" >&2; exit 1; fi
    echo "   $(basename "$f"): $rows rows"
  done
done
# deck 14 also writes a ready-made CSV (the mains / capacitor case table)
cp build/14-cases.csv "$OUT/14-cases.csv"
echo "done: CSVs in $OUT"
